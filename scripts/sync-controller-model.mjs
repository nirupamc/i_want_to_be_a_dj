import * as fs from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const source = path.join(root, 'src', 'three', 'ddj-flx4', 'ddj-flx4-controller.glb')
const runtime = path.join(root, 'public', 'models', 'ddj-flx4', 'ddj-flx4-controller.glb')
const versionFile = path.join(root, 'src', 'three', 'ddj-flx4', 'controllerModelVersion.ts')

function sha256(file) {
  return createHash('sha256').update(fs.readFileSync(file)).digest('hex').toUpperCase()
}

if (!fs.existsSync(source)) {
  console.error(`Controller source model is missing: ${source}`)
  process.exit(1)
}

fs.mkdirSync(path.dirname(runtime), { recursive: true })
fs.copyFileSync(source, runtime)

const sourceHash = sha256(source)
const runtimeHash = sha256(runtime)
if (sourceHash !== runtimeHash) {
  console.error('Controller model sync failed: source and runtime hashes differ.')
  console.error(`source : ${sourceHash}`)
  console.error(`runtime: ${runtimeHash}`)
  process.exit(1)
}

const version = runtimeHash.slice(0, 12).toLowerCase()
const versionSource = `// Generated by scripts/sync-controller-model.mjs.\nexport const CONTROLLER_MODEL_VERSION = "${version}"\n`
if (!fs.existsSync(versionFile) || fs.readFileSync(versionFile, 'utf8') !== versionSource) {
  fs.writeFileSync(versionFile, versionSource, 'utf8')
}

const stat = fs.statSync(runtime)
console.log(`Synced controller model: ${path.relative(root, source)} -> ${path.relative(root, runtime)}`)
console.log(`Size: ${stat.size} bytes`)
console.log(`SHA256: ${runtimeHash}`)
console.log(`Version: ${version}`)
